// 정수 리터럴
package study.lang.literal;

public class Exam02 {
  public static void main(String[] args){

    System.out.println(100); // 10진수
    System.out.println(0144); // 8진수
    System.out.println(0x64); // 16진수, 실무
    System.out.println(0X64); // 16진수
    System.out.println(0b01100100); // 2진수
    System.out.println(0B01100100); // 2진수

    System.out.println(32_768); // 10진수
    System.out.println(01_44); // 8진수
    System.out.println(0x6_4); // 16진수, 실무
    System.out.println(0b0110_0100); // 2진수
  }
}
