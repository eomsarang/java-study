// 산술 연산자
package study.lang.operator;

public class Exam01 {

  public static void main(String[] args) {
    System.out.println(100 + 200);
    System.out.println(100 - 200);
    System.out.println(100 * 200);
    System.out.println(100 / 200); // 정수와 정수의 연산 결과는 같은 타입인 정수이다.
    System.out.println(100 % 200);

    System.out.println(100.0 + 200.0);
    System.out.println(100.0 - 200.0);
    System.out.println(100.0 * 200.0);
    System.out.println(100.0 / 200.0);
    System.out.println(100.0 % 200.0);
  }
}
